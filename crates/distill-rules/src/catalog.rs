#[allow(clippy::too_many_arguments)]
const fn rule(
    path: &'static [&'static str],
    family: &'static str,
    priority: u16,
    severity: Severity,
    effect: Option<EffectKind>,
    id: &'static str,
    impact: &'static str,
    partial: bool,
    unknown: Option<&'static str>,
) -> RuleDef {
    RuleDef {
        path,
        family,
        priority,
        severity,
        effect,
        id,
        impact,
        partial,
        unknown,
        basis: FindingBasis::Impact,
    }
}

const fn uncertainty(mut rule: RuleDef) -> RuleDef {
    rule.basis = FindingBasis::Uncertainty;
    rule
}

struct RuleSet {
    trie: TokenTrie,
    rules: &'static [RuleDef],
}

impl RuleSet {
    fn load() -> Self {
        let rules = CATALOG;
        let mut trie = TokenTrie::new();
        for (index, rule) in rules.iter().enumerate() {
            trie.insert(rule.path, (index + 1) as u16);
        }
        for flag in [
            "--force",
            "--recursive",
            "--interactive",
            "--interactive=once",
            "--verbose",
            "--dir",
            "-f",
            "-i",
            "-I",
            "-v",
            "-d",
        ] {
            trie.insert(&["rm", flag], 0);
        }
        for flag in ["--formula", "--cask", "--zap", "-f"] {
            trie.insert(&["brew", "uninstall", flag], 0);
        }
        Self { trie, rules }
    }

    fn considers(&self, tokens: &[&str]) -> Vec<FiredRule> {
        let mut best: Vec<usize> = Vec::new();
        for id in self.trie.collect(tokens) {
            let index = id as usize - 1;
            let rule = &self.rules[index];
            if let Some(slot) = best
                .iter()
                .position(|existing| self.rules[*existing].family == rule.family)
            {
                if rule.priority >= self.rules[best[slot]].priority {
                    best[slot] = index;
                }
            } else {
                best.push(index);
            }
        }
        best.into_iter()
            .map(|index| {
                let rule = &self.rules[index];
                FiredRule {
                    severity: rule.severity,
                    effect: rule.effect,
                    id: rule.id,
                    impact: rule.impact,
                    partial: rule.partial,
                    unknown: rule.unknown,
                    basis: rule.basis,
                }
            })
            .collect()
    }

    fn recognizes(&self, prefix: &[&str], token: &str) -> bool {
        self.trie.recognizes(prefix, token)
    }
}

fn rules() -> &'static RuleSet {
    static RULES: OnceLock<RuleSet> = OnceLock::new();
    RULES.get_or_init(RuleSet::load)
}

pub fn considers(tokens: &[&str]) -> Vec<FiredRule> {
    rules().considers(tokens)
}
pub fn recognizes(prefix: &[&str], token: &str) -> bool {
    rules().recognizes(prefix, token)
}
